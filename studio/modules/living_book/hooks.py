def on_before_agent(state: dict, worker_id: str, context: str) -> str:
    """Вызывается ПЕРЕД каждым агентом. Можно модифицировать контекст.

    Args:
        state: глобальный state
        worker_id: ID агента (A00, A00a, A01, ...)
        context: собранный контекст для агента

    Returns:
        Модифицированный контекст (или тот же если не менять)

    Примеры:
        - Добавить данные ребёнка в контекст A00 (Фабула)
        - Инжектировать психологические протоколы для A00a (Вера)
        - Передать аудио-параметры для A05 (звуковой дизайн)
    """

    # Фабула получает детали ребёнка
    if worker_id == "A00":
        child_info = state.get("child_info", {})
        if child_info:
            context += f"\n\n=== ДАННЫЕ РЕБЁНКА ===\n"
            context += f"Имя: {child_info.get('name', 'не указано')}\n"
            context += f"Возраст: {child_info.get('age', 'не указан')}\n"
            context += f"Интересы: {child_info.get('interests', 'не указаны')}\n"
            context += f"Особенности: {child_info.get('notes', 'нет')}\n"
            context += f"=== КОНЕЦ ДАННЫХ РЕБЁНКА ===\n"

    # Вера Душа получает дополнительные критерии
    if worker_id == "A00a":
        context += (
            "\n\n=== КРИТЕРИИ ПРОВЕРКИ ===\n"
            "1. Безопасность: нет пугающих элементов для целевого возраста\n"
            "2. Привязанность: история создаёт чувство безопасной базы\n"
            "3. Персонализация: ребёнок узнает себя в герое\n"
            "4. Эмоциональная дуга: от тревоги к разрешению через поддержку\n"
            "=== КОНЕЦ КРИТЕРИЕВ ===\n"
        )

    return context


def on_after_agent(state: dict, worker_id: str, human_text: str, meta: dict) -> dict:
    """Вызывается ПОСЛЕ каждого агента. Можно обработать результат.

    Args:
        state: глобальный state
        worker_id: ID агента
        human_text: текстовый результат агента
        meta: метаданные ответа

    Returns:
        dict с полями для перезаписи: {"human_text": ..., "meta": ...}
        Или пустой dict если не менять.

    Примеры:
        - Извлечь chapter_data из ответа A01 и сохранить в state
        - Проверить что A05 включил аудио-параметры
        - Собрать book_package из результатов A13-A16
    """

    # После A00 (Фабула) — сохраняем сюжетный каркас
    if worker_id == "A00":
        state["story_framework"] = human_text[:2000]

    # После A16 (финальный) — собираем итоговый пакет
    if worker_id == "A16":
        state["book_complete"] = True
        print(f"[LIVING_BOOK] 📖 Книга завершена!")

    return {}


def on_revision_notes(state: dict, notes: str, loop_number: int) -> str:
    """Вызывается при РЕВИЗИИ — можно усилить замечания Веры.

    Args:
        state: глобальный state
        notes: замечания от Веры Души
        loop_number: номер ревизии (1, 2, 3)

    Returns:
        Модифицированные замечания для Фабулы

    Пример: на 3-й ревизии добавить строгий тон.
    """
    if loop_number >= 3:
        notes += (
            "\n\n⚠️ ТРЕТЬЯ РЕВИЗИЯ. Это последняя попытка. "
            "Сосредоточься на главном замечании и исправь его полностью."
        )

    return notes


