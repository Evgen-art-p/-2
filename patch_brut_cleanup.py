#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ═══════════════════════════════════════════════════════════════
# ПАТЧ-ПОДЧИСТКА: убрать призрак Air Bag из описаний Брута
# patch_brut_cleanup.py · 2026-06-18
#
# Логика Брута ПРАВИЛЬНАЯ. Врут только тексты-описания — остались
# ссылки на то, чего на столе нет:
#   · prompt.md «ВОТ СЕЙЧАС»: «подушка безопасности» + «лента сессии»
#     (air_bag ядро не считает; лента сессии — будущий этап).
#   · brut_live.py комментарий п.4: «Air Bag» в перечислении.
#
# Меняем ТОЛЬКО строки-описания. Ни одной строки логики не трогаем.
# Идемпотентный: если призрака уже нет — сообщает и не портит.
# С бэкапом каждого тронутого файла.
# ═══════════════════════════════════════════════════════════════

import shutil
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TRADING = ROOT / "studio" / "modules" / "trading"
PROMPT = TRADING / "A06" / "forge" / "prompt.md"
BRUT   = TRADING / "brut_live.py"

if not TRADING.exists():
    print(f"❌ Не нашёл {TRADING}. Запусти из корня репозитория.")
    raise SystemExit(1)

stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
changed = []

# ── 1. prompt.md — раздел «ВОТ СЕЙЧАС» ──────────────────────
# Старый абзац обещает подушку безопасности и ленту сессии, которых
# на столе нет. Заменяем на честное перечисление того, что реально лежит.
PROMPT_OLD = """Перед тобой — **раскладка момента**: что считало ядро на этом баре и в этой
сессии. Якорь (куда смотрит старший ТФ), лесенка таймфреймов, индикаторы,
хозяин бара, подушка безопасности, лента сессии — кто из сенсоров уже ударил
и когда. Цифры посчитаны за тебя; ты их не пересчитываешь — ты их читаешь."""

PROMPT_NEW = """Перед тобой — **раскладка момента**: что считало ядро на этом баре. Якорь
(куда смотрит старший ТФ — глобальный тренд), индикаторы, Аллигатор и его
Зубы (Красная линия — граница пасти), фракталы за пастью, хозяин бара (OHLC),
и показания сенсоров — кто из них уже подал голос. Цифры посчитаны за тебя;
ты их не пересчитываешь — ты их читаешь."""

if PROMPT.exists():
    txt = PROMPT.read_text(encoding="utf-8")
    if PROMPT_OLD in txt:
        shutil.copy2(PROMPT, PROMPT.with_suffix(PROMPT.suffix + f".bak_{stamp}"))
        txt = txt.replace(PROMPT_OLD, PROMPT_NEW)
        PROMPT.write_text(txt, encoding="utf-8")
        changed.append("A06/forge/prompt.md (раздел «ВОТ СЕЙЧАС»)")
        print("✅ prompt.md: убраны подушка безопасности и лента сессии")
    elif PROMPT_NEW.split("\n")[0] in txt:
        print("ℹ️  prompt.md: уже подчищен — пропускаю")
    else:
        print("⚠️  prompt.md: не нашёл ожидаемый абзац — глянь вручную")
else:
    print(f"⚠️  {PROMPT} не найден")

# ── 2. brut_live.py — комментарий п.4 ───────────────────────
BRUT_OLD = """    # ── 4. РАСКЛАДКА МОМЕНТА — то, что код кладёт Бруту на стол ──
    # Якорь, индикаторы, хозяин бара, Air Bag, фрактал-ориентир Ганса.
    # Брут НЕ пересчитывает — читает и СЧИТАЕТ свой вход из этих чисел."""

BRUT_NEW = """    # ── 4. РАСКЛАДКА МОМЕНТА — то, что код кладёт Бруту на стол ──
    # Якорь, индикаторы, Зубы (Красная), фракталы за пастью, хозяин бара,
    # фрактал-ориентир Ганса. Брут НЕ пересчитывает — читает и СЧИТАЕТ
    # свой вход из этих чисел. Стоп — под противоположный фрактал (§8),
    # это его рычаг, не рельса."""

if BRUT.exists():
    txt = BRUT.read_text(encoding="utf-8")
    if "Air Bag, фрактал-ориентир Ганса" in txt:
        shutil.copy2(BRUT, BRUT.with_suffix(BRUT.suffix + f".bak_{stamp}"))
        txt = txt.replace(BRUT_OLD, BRUT_NEW)
        BRUT.write_text(txt, encoding="utf-8")
        changed.append("brut_live.py (комментарий п.4)")
        print("✅ brut_live.py: убран призрак Air Bag из комментария")
    elif "Зубы (Красная), фракталы за пастью" in txt:
        print("ℹ️  brut_live.py: уже подчищен — пропускаю")
    else:
        print("⚠️  brut_live.py: не нашёл ожидаемый комментарий — глянь вручную")
else:
    print(f"⚠️  {BRUT} не найден")

# ── проверка: brut_live.py остался валидным Python ──
if BRUT.exists():
    import ast
    try:
        ast.parse(BRUT.read_text(encoding="utf-8"))
        print("🎯 brut_live.py синтаксис цел")
    except SyntaxError as e:
        print(f"❌ brut_live.py сломан: {e} — восстанови из .bak_{stamp}")

print()
if changed:
    print("Подчищено:", *changed, sep="\n  · ")
    print("\nЛогику не трогали — только описания. Брут больше не ищет")
    print("на столе подушку безопасности и ленту сессии, которых нет.")
else:
    print("Менять было нечего — описания уже чистые.")
