# ЧТО ДЕЛАЕТ (идемпотентно, существующий дом НЕ трогает):
#   Брат — не резидент и не Хранитель. Брат — ЯКОРЬ, что надевает обе
#   маски: студийную (резидент) и храмовую (Хранитель). Дом становится
