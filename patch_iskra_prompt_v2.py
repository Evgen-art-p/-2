"""
patch_iskra_prompt_v2.py — РАЗРЫВ 1 контура Искры v2 (§1e мастер-контекста)

ЧТО ЧИНИТ (на пальцах):
  У Искры появилось новое зрение — спуск по лесенке ТФ (геометрия уже работает
  в коде, кладёт результат в v2_descent). Но её голова (промт) этого зрения
  не знает: учит старому — «флаг divergence_ao одного бара = твой ориентир».
  Два разных указания → на найденной точке Искра запутается.

ЧТО ДЕЛАЕТ (три точечные правки, характер НЕ трогаем):
  1. divergence_ao переописан: сырой флаг ОДНОГО бара, для отладки — не главный.
  2. «signal = divergence_ao» → «signal = результат спуска (v2_descent)».
  3. Добавлен раздел «ТВОЁ ЗРЕНИЕ ВГЛУБЬ — СПУСК» + два новых поля signal
     (trend_direction, found_timeframe) в формат ответа.

НЕ ТРОГАЕТ: «КТО ТЫ», характер, душу, закон «кричу факт не команду»,
  бычью/медвежью дивергенцию как понятия. Меняется только ОПИСАНИЕ зрения.

БЕЗОПАСНОСТЬ: идемпотентен (маркер), бэкап .bak, якорный replace, CRLF-safe.
"""
import shutil
from datetime import datetime
from pathlib import Path

TARGET = Path("studio/modules/trading/A01/forge/prompt.md")
MARKER = "ISKRA_PROMPT_V2"


# ── Правка 1: строка про divergence_ao ───────────────────────────────
OLD_1 = "market_data.divergence_ao ← флаг дивергенции (по двум последним пивотам) — твой ориентир"
NEW_1 = "market_data.divergence_ao ← СЫРОЙ флаг дивергенции одного бара (для отладки) — НЕ твой главный сигнал"

# ── Правка 2: абзац «signal должен совпадать с divergence_ao» ─────────
OLD_2 = """Движок уже посчитал пивоты — ты их НЕ ищешь глазами по цене, ты ЧИТАЕШЬ готовые
`ao.pivots`. Это синхронизирует твой голос с движком: твой `t1_status` (signal)
должен совпадать с флагом `divergence_ao`. Голос (narrative) может рассуждать шире,
но сигнал — это факт движка, не твоя фантазия."""

NEW_2 = """Движок уже посчитал пивоты — ты их НЕ ищешь глазами по цене, ты ЧИТАЕШЬ готовые
`ao.pivots` как опору. Но твой ГЛАВНЫЙ сигнал теперь рождается не из флага одного
бара, а из СПУСКА ПО ЛЕСЕНКЕ (см. раздел «ТВОЁ ЗРЕНИЕ ВГЛУБЬ» ниже). Голос
(narrative) рассуждает шире, но `t1_status` (signal) ты ставишь по результату
спуска, который геометрия уже принесла тебе в блоке `v2_descent`."""

# ── Правка 3: новый раздел «ТВОЁ ЗРЕНИЕ ВГЛУБЬ» — вставляем ПЕРЕД хвостом ──
ANCHOR_3 = """---

*Кристаллизация 1/9. Следующий: A02 Морж — он отсчитает масштаб от твоей Точки Ноль.*"""

INSERT_3 = """## ТВОЁ ЗРЕНИЕ ВГЛУБЬ — СПУСК ПО ЛЕСЕНКЕ  <!-- """ + MARKER + """ -->

У тебя есть новое чувство — спуск по лесенке таймфреймов (D1 → H12 → H8 → H4
→ ... → M5). Это твоё зрение ВГЛУБЬ. Слепая геометрия проходит лесенку ДО того,
как ты вдохнёшь, и приносит тебе готовый результат в блоке `v2_descent`:

```
v2_descent.compass      ← КОМПАС: сторона разворота (BULL/BEAR) или нет дивера-с-якорем
v2_descent.start_tf      ← с какого этажа взят компас (старший ТФ)
v2_descent.found         ← нашлась ли точка B/D/B в сторону компаса (true/false)
v2_descent.timeframe     ← НА КАКОМ этаже нашлась точка (если found)
v2_descent.zero_point    ← цена найденной точки (если found)
```

Как ты этим видишь и говоришь:
- **Компас = None** (нет дивера-с-якорем-царём) — ловить нечего. `t1_status=NOT_FOUND`.
  Молчишь честно, как всегда молчала.
- **Компас есть, но точка НЕ найдена** (`found=false`) — спуск дошёл до дна M5,
  чистого B/D/B нет. Откат ещё не дозрел или зигзаг не сложился. `t1_status=NOT_FOUND`.
- **Точка найдена** (`found=true`) — вот оно, дно отката. `t1_status=DETECTED`,
  `trend_direction` = компас, `zero_point_price` = цена точки,
  `found_timeframe` = этаж, где нашлась (Морж встанет на тот же масштаб).

Закон тот же, что всегда: ты не врёшь о том, что видишь. Геометрия — твоё зрение,
оно честное. Твоё дело — озвучить увиденное своим голосом и поставить статус по нему.

---

"""


def apply(src: str, old: str, new: str, label: str) -> tuple[str, bool]:
    """Якорный replace с фоллбэком на CRLF. Возвращает (текст, успех)."""
    if new in src and old not in src:
        print(f"   ↳ {label}: уже применено — пропускаю.")
        return src, True
    if old in src:
        return src.replace(old, new, 1), True
    old_cr = old.replace("\n", "\r\n")
    if old_cr in src:
        return src.replace(old_cr, new.replace("\n", "\r\n"), 1), True
    print(f"   ❌ {label}: якорь не найден.")
    return src, False


def main():
    if not TARGET.exists():
        print(f"❌ Не найден файл: {TARGET}")
        return

    src = TARGET.read_text(encoding="utf-8")

    if MARKER in src:
        print(f"✅ Уже пропатчено (маркер {MARKER}) — ничего не делаю.")
        return

    ok_all = True
    src, ok = apply(src, OLD_1, NEW_1, "Правка 1 (divergence_ao)"); ok_all &= ok
    src, ok = apply(src, OLD_2, NEW_2, "Правка 2 (signal по спуску)"); ok_all &= ok
    src, ok = apply(src, ANCHOR_3, INSERT_3 + ANCHOR_3, "Правка 3 (раздел зрения)"); ok_all &= ok

    if not ok_all:
        print("⚠️  Не все якоря найдены — ничего не записано (безопасно).")
        print("    Скорее всего промт уже редактировался. Покажи мне его — поправлю якоря.")
        return

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    bak = TARGET.with_suffix(TARGET.suffix + f".bak_{stamp}")
    shutil.copy2(TARGET, bak)
    print(f"💾 Бэкап: {bak.name}")

    TARGET.write_text(src, encoding="utf-8")
    print("✅ Голова Искры обновлена: один начальник — спуск. Старый флаг разжалован в отладку.")


if __name__ == "__main__":
    main()
